"""cc-P856: the five winter pieces' component lists, read out of the downloads' YAAAG addon scripts, written as our own
C# design table (server/customizations/WinterSet/WinterSetDesigns.cs). Only the numbers are read (item ID, x, y, z, and
for the "complex" components hue, light and name); no code is taken. P855's convert.py, retargeted at a C# table
because P855's data addon had not merged into main when P856 ran.

  python -P convert856.py <third-party code folder> <output .cs>

Prints each design's component count against the source's, its footprint and its lights.
"""

import os
import re
import sys

# pinned Projects/Server/Items/LightType.cs, in order (only the values these files use).
LIGHT_NAMES = {0: "ArchedWindowEast", 1: "Circle225", 2: "Circle150", 29: "Circle300"}

# (folder, file inside it, our key, display name, credit line)
PIECES = [
    ("celestial-christmas-train", "Christmas_TrainAddon.cs", "christmas-train", "a Christmas train", "Celestial"),
    ("milva-snowglobe", "NewLargeSnowGlobeAddon.cs", "large-snow-globe", "a large snow globe", "Milva"),
    ("candyapple-xmas-deco", "X-Mas Deco/SantaBenchAddon.cs", "santa-bench", "a Santa bench", "Candy Apple"),
    ("candyapple-xmas-deco", "X-Mas Deco/SnowmanBenchAddon.cs", "snowman-bench", "a snowman bench", "Candy Apple"),
    ("lagatha-holiday-fireplace", "holidayfireplaceAddon.cs", "holiday-fireplace", "a holiday fireplace",
     "Lagatha, after Gwenivere (Knights of the Round Table shard)"),
]

SIMPLE = re.compile(r"\{\s*(\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*\}")
COMPLEX = re.compile(r"AddComplexComponent\(\s*\(BaseAddon\)\s*this\s*,([^;]*)\)\s*;")


def source_url(folder):
    with open(os.path.join(folder, "SOURCE.txt"), encoding="utf-8-sig") as f:
        for line in f:
            if line.startswith("http"):
                return line.strip()
    return ""


def parse(path):
    text = open(path, encoding="utf-8", errors="replace").read()
    pieces = []
    m = re.search(r"m_AddOnSimpleComponents\s*=\s*new int\[,\]\s*\{(.*?)\};", text, re.S)
    if m:
        for g in SIMPLE.findall(m.group(1)):
            pieces.append((int(g[0]), int(g[1]), int(g[2]), int(g[3]), 0, -1, ""))
    for args in COMPLEX.findall(text):
        parts = [a.strip() for a in args.split(",")]
        item, x, y, z, hue, light = (int(p) for p in parts[:6])
        name = parts[6].strip('"') if len(parts) > 6 else ""
        amount = int(parts[7]) if len(parts) > 7 else 1
        if amount != 1:
            raise ValueError(f"{path}: amount {amount}")
        pieces.append((item, x, y, z, hue, light, name))
    expected = len(re.findall(r"AddComplexComponent\(\s*\(BaseAddon\)", text)) + (len(SIMPLE.findall(m.group(1))) if m else 0)
    return pieces, expected


def cs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    src, out = sys.argv[1], sys.argv[2]
    lines = [
        "// GENERATED by shard-migration notes/cc-P856-tools/convert856.py from the downloads' component lists. Do not edit by",
        "// hand: rerun the script. cc-P856: the New Haven winter set's five pieces, stock client art only. Each row: item ID,",
        "// x, y, z offset from the addon's tile, hue, light (or null) and name (or null). Credits are each design's own.",
        "",
        "using System.Collections.Generic;",
        "",
        "namespace Server.Items;",
        "",
        "public static class WinterSetDesigns",
        "{",
        "    public static readonly Dictionary<string, WinterSetDesign> All = new()",
        "    {",
    ]
    for folder, file, key, display, credit in PIECES:
        pieces, expected = parse(os.path.join(src, folder, file))
        assert len(pieces) == expected and pieces, (file, len(pieces), expected)
        xs = [p[1] for p in pieces]
        ys = [p[2] for p in pieces]
        zs = [p[3] for p in pieces]
        lights = sorted({p[5] for p in pieces if p[5] != -1})
        print(f"{key}: {len(pieces)} components, x {min(xs)}..{max(xs)}, y {min(ys)}..{max(ys)}, z {min(zs)}..{max(zs)}, lights {lights}")
        lines.append(f"        // {folder}/{file} ({source_url(os.path.join(src, folder))}), by {credit}.")
        lines.append(f"        [{cs(key)}] = new({cs(key)}, {cs(display)}, {cs(credit)},")
        lines.append("        [")
        for item, x, y, z, hue, light, name in pieces:
            lt = f"LightType.{LIGHT_NAMES[light]}" if light != -1 else "null"
            nm = cs(name) if name else "null"
            lines.append(f"            new(0x{item:04X}, {x}, {y}, {z}, {hue}, {lt}, {nm}),")
        lines.append("        ]),")
    lines += ["    };", "}", ""]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
