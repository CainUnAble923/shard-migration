"""cc-P760: writes the store shots' spec (shots760.json) and one Legion script per store (StoreShot760-<name>.py) beside
this file. Each store scene: the Golem's Admin moves the Tester and grants the store's currency; TazUO logs the Tester
in; the script speaks the command that opens the store, asks the runner (store-shots.ps1's signal file) for a shot of
the window, presses a row to open the confirm step, asks for a shot, and (where set) presses Buy and asks for a last
shot of the window again with the lower balance.

    python -P make_shots.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PROOF = r"D:/UO/golems/Iron/p760-proof"
WHO = "Iron the Tester"


def move(x, y, z):
    loc = f"({x},{y},{z})"
    w = f'where playermobile Name == "{WHO}"'
    return [
        f"[global resurrect {w}",
        f"[global set Blessed True {w}",
        f"[global set Map Trammel {w}",
        f"[global set Location {loc} {w}",
        f"[global set LogoutMap Trammel {w}",
        f"[global set LogoutLocation {loc} {w}",
    ]


SCRIPT = '''# cc-P760 (generated by make_shots.py): opens {title} and asks for shots of the window and its confirm step.
import API

SIG = r"{sig}"
LOG = r"{log}"


def note(text):
    with open(LOG, "a") as f:
        f.write(text + "\\n")
    API.SysMsg("P760: " + text)


def shot(name):
    with open(SIG, "a") as f:
        f.write("SHOT " + name + "\\n")
    API.Pause(2)


API.Pause(4)
note("opening {title} with: {say}")
API.Msg("{say}")
API.Pause(4)
shot("{name}-window")
API.ReplyGump({row})
API.Pause(4)
shot("{name}-confirm")
if {buy}:
    API.ReplyGump(1)
    API.Pause(4)
    shot("{name}-after-buy")
note("done")
with open(SIG, "a") as f:
    f.write("DONE\\n")
'''

SCENES = [
    # name, title, where the Tester stands, grants, what he says, the row button pressed (200 + row index), buy it
    ("festival", "the Festival store", (3636, 2630, 0), ["tokens 40"], "festival", 201, True),
    # The Rangers' League guildmaster stands here in Trammel's New Haven (the smith and tailor guildmasters first tried
    # were Felucca's old Haven, at the same coordinates). "guild store" said to him, then the arrows row's confirm step.
    ("guild", "the Rangers' League store", (3654, 2618, 0), ["guild:rangers 15000"], "guild store", 202, False),
    ("guildcmd", "the Rangers' League store by command", (3654, 2618, 0), ["guild:rangers 0"], "[guildstore", 203, False),
    ("apstore", "the Achievement store", (3640, 2560, 0), ["ap 600"], "[apstore", 209, True),
    ("league", "the League shop", (3640, 2560, 0), ["renown 2000", "ap 600"], "[leagueshop", 220, True),
]


def main():
    shots = [
        {
            # the stall from the north-west, the default camera, the Tester three tiles off (the guide's section 8)
            "name": "stall-outside",
            "settle": 20,
            "commands": move(3633, 2624, 0),
        },
        {
            "name": "stall-south",
            "settle": 20,
            "commands": move(3636, 2633, 0),
        },
    ]
    for name, title, (x, y, z), grants, say, row, buy in SCENES:
        sig = f"{PROOF}/{name}-signal.txt"
        script = f"StoreShot760-{name}.py"
        with open(os.path.join(HERE, script), "w", encoding="ascii", newline="\n") as f:
            f.write(SCRIPT.format(title=title, sig=sig, log=f"{PROOF}/{name}.log", say=say, name=name, row=row, buy=buy))
        shots.append({
            "name": f"{name}-login",
            "legion": script,
            "settle": 10,
            "sig": sig,
            "maxSeconds": 120,
            "commands": move(x, y, z) + [f"[RewardStores grant {WHO} {g}" for g in grants],
        })
    with open(os.path.join(HERE, "shots760.json"), "w", encoding="ascii", newline="\n") as f:
        json.dump(shots, f, indent=1)
    print(len(shots), "shots")


if __name__ == "__main__":
    main()
