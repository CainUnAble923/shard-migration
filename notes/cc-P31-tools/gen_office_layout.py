# cc-P31: successor of notes/cc-P19-tools/gen_office_layout.py. WRITES three files in D:\ShatteredLegacy:
#   D:/ShatteredLegacy/design/registrar-office/layout.json
#     -> server/customizations/ClusterFRegistrarOfficeLayout.cs     (the table the server uses)
#     -> server/tests/Misc/RegistrarOfficeLayoutDesignCopy.cs        (the design file verbatim, for the test)
#   D:/ShatteredLegacy/design/registrar-office/cleanup/layout_p19.json
#     -> server/tests/Misc/RegistrarOfficeLayoutP19Copy.cs           (P19's layout verbatim: the fixture for the
#                                                                     replace facts, a world seeded by P19)
# The first two are byte-for-byte what P19's generator writes, apart from the generator path in the header.
# The test parses the verbatim copies and checks their SHA-256 against the hashes recorded here. Re-run this
# after any change to layout.json.
# Hash: SHA-256 of the file's text with CRLF normalized to LF and trailing newlines removed.
import hashlib, json
ROOT = r'D:/ShatteredLegacy'
DESIGN = ROOT + '/design/registrar-office/layout.json'
P19 = ROOT + '/design/registrar-office/cleanup/layout_p19.json'
GEN = 'notes/cc-P31-tools/gen_office_layout.py'
AREAS = ['outside', 'office', 'quarters']                 # one addon per area, in this order


def load(path):
    raw = open(path, 'rb').read().decode('ascii')          # ASCII only; fails loudly otherwise
    text = raw.replace('\r\n', '\n').rstrip('\n')
    assert '"""' not in text
    L = json.loads(text)
    assert sorted(set(c['area'] for c in L['components'])) == sorted(AREAS), set(c['area'] for c in L['components'])
    return text, hashlib.sha256(text.encode('ascii')).hexdigest(), L


def q(s): return json.dumps(s)


def verbatim(cls, sha, text, lead):
    t = [f'// Generated by shard-migration {GEN}. Do not edit by hand.', '//']
    t += lead
    t += ['', 'namespace ShatteredLegacy.Tests;', '', f'internal static class {cls}', '{',
          f'    public const string Sha256 = "{sha}";', '', '    public const string Json =', '"""', text, '""";', '}']
    return '\n'.join(t) + '\n'


text, sha, L = load(DESIGN)
text19, sha19, L19 = load(P19)

out = []
w = out.append
w(f'// Generated by shard-migration {GEN} from design/registrar-office/layout.json.')
w('// Do not edit by hand: change the design file and re-run the generator. The test')
w('// RegistrarOfficeVerification.TheLoadedLayoutIsTheDesignFile compares this table with the design file.')
w('//')
w('// The layout is a C# table, not a data file, for cc-P16\'s reason: the build installs only .cs files from')
w('// server/customizations (docker/uo/apply-patches.sh, mirror_cs_tree), and Distribution/Data is pinned.')
w('// Components use cc-P16\'s MineCampComponent record (ClusterFMineCampLayout.cs); Group is the design\'s area.')
w('')
w('namespace Server;')
w('')
w('public static class ClusterFRegistrarOfficeLayout')
w('{')
w('    public const string DesignFile = "design/registrar-office/layout.json";')
w(f'    public const string DesignSha256 = "{sha}";')
w(f'    public const string MapName = {q(L["map"])};')
w('')
w('    // In design order.')
w('    public static readonly MineCampComponent[] Components =')
w('    [')
for c in L['components']:
    w(f'        new({q(c["area"])}, 0x{int(c["id"], 16):04X}, {q(c["name"])}, {c["x"]}, {c["y"]}, {c["z"]}),')
w('    ];')
w('')
for a in AREAS:
    w(f'    public static readonly MineCampComponent[] {a.capitalize()} =')
    w('    [')
    for c in L['components']:
        if c['area'] == a:
            w(f'        new({q(c["area"])}, 0x{int(c["id"], 16):04X}, {q(c["name"])}, {c["x"]}, {c["y"]}, {c["z"]}),')
    w('    ];')
    w('')
w('    public static readonly (string Area, MineCampComponent[] Components)[] Areas =')
w('    [')
for a in AREAS:
    w(f'        ({q(a)}, {a.capitalize()}),')
w('    ];')
w('}')
open(ROOT + '/server/customizations/ClusterFRegistrarOfficeLayout.cs', 'w', newline='\n').write('\n'.join(out) + '\n')

open(ROOT + '/server/tests/Misc/RegistrarOfficeLayoutDesignCopy.cs', 'w', newline='\n').write(verbatim(
    'RegistrarOfficeLayoutDesignCopy', sha, text, [
        '// design/registrar-office/layout.json, verbatim. The test container holds server/tests but not design/',
        '// (docker/uo/Dockerfile copies only server/customizations, server/tests, server/migrations and',
        '// server/patches), so the design file reaches the test as this copy. Its SHA-256 is checked against',
        '// the hash the generator recorded from the design file.',
    ]))

open(ROOT + '/server/tests/Misc/RegistrarOfficeLayoutP19Copy.cs', 'w', newline='\n').write(verbatim(
    'RegistrarOfficeLayoutP19Copy', sha19, text19, [
        '// design/registrar-office/cleanup/layout_p19.json, verbatim: the layout cc-P19 shipped, kept by the overseer',
        '// beside the current design. The replace facts build a world seeded by cc-P19 from it. It reaches the',
        '// test container the same way as RegistrarOfficeLayoutDesignCopy, with the same hash check.',
    ]))

for name, LL, h in (('layout.json', L, sha), ('layout_p19.json', L19, sha19)):
    print(name, 'components:', len(LL['components']),
          {a: sum(c['area'] == a for c in LL['components']) for a in AREAS}, 'sha256:', h)
