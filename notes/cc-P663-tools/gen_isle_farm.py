"""cc-P663 (P481 F3): the tutorial farm on the Wakening Isle, generated from P276's approved New Haven layout.

Every piece of TutorialFarmLayout.cs moves by FARM_SHIFT and keeps its height above the old ground (P481 11.2): the new
Z is the old Z minus the vanilla Trammel land Z under that tile, never below 0. The isle's meadow is flat at Z 0, so that
height is the piece's Z on the isle. The farmhouse door (not a layout row) moves the same way.

  python -P gen_isle_farm.py            (MAPBUILD_CLIENT: the vanilla client folder; SL_CODE: the code work copy)

Writes server/customizations/Tutorial/TutorialIsleFarmLayout.cs in the code work copy. The ground is read from the
vanilla files, the land the farm was designed on, not from whatever map the server runs later (the SoS swap turns the
old site into forest).
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, "scripts"))
from mapbuild import uofiles  # noqa: E402

# P673 1.4: the farm's shift from New Haven to site A (P481's (+2890, -628) to void C, plus (+424, +1992)).
FARM_SHIFT = (3314, 1364)


def main():
    code = os.environ.get("SL_CODE", os.path.join(os.path.dirname(REPO), "ShatteredLegacy"))
    src_path = os.path.join(code, "server", "customizations", "Tutorial", "TutorialFarmLayout.cs")
    src = open(src_path, encoding="utf-8").read()
    # Only the Pieces table: RemovedTrees above it has the same row shape (P481's newisle.py counted those 4 in, 334).
    rows = re.findall(r"\((0x[0-9A-Fa-f]+), (\d+), (\d+), (-?\d+)\), // (.*)", src[src.index("Pieces ="):])
    anchor = tuple(int(v) for v in re.search(r"Anchor = new\((\d+), (\d+), (-?\d+)\)", src).groups())
    door = tuple(int(v) for v in re.search(r"DoorSpot = new\((\d+), (\d+), (-?\d+)\)", src).groups())
    mf = uofiles.MapFile(uofiles.CLIENT, 1)

    def moved(x, y, z):
        return x + FARM_SHIFT[0], y + FARM_SHIFT[1], max(0, z - mf.get(x, y)[1])

    out = []
    clipped = 0
    for tid, x, y, z, name in rows:
        x, y, z = int(x), int(y), int(z)
        if z < mf.get(x, y)[1]:
            clipped += 1
        nx, ny, nz = moved(x, y, z)
        out.append("        (%s, %d, %d, %d), // %s" % (tid, nx, ny, nz, name.strip()))
    ax, ay, _ = moved(*anchor)
    dx, dy, dz = moved(*door)

    text = """// cc-P663 (P481 F3): the tutorial farm on the Wakening Isle. GENERATED by shard-migration
// notes/cc-P663-tools/gen_isle_farm.py from TutorialFarmLayout.cs (P276's approved layout): do not edit by hand. Every
// piece moves by ({sx}, {sy}) (P673 1.4) and keeps its height above the vanilla Trammel ground it stood on in New Haven
// (P481 11.2); the isle's meadow is flat at Z 0, so that height is its Z here. Coordinates are absolute, on the lesson
// map (TutorialWorld). {n} rows; {clipped} stood below the old ground (none is clipped).

namespace Server.Tutorial;

public static class TutorialIsleFarmLayout
{{
    /// <summary>The shift from P276's New Haven farm to the isle's.</summary>
    public static readonly Point2D Shift = new({sx}, {sy});

    /// <summary>The farmhouse's centre (the addon's anchor), on the meadow at Z 0.</summary>
    public static readonly Point3D Anchor = new({ax}, {ay}, 0);

    /// <summary>The farmhouse door (east wall), dark wood, at its height above the old ground.</summary>
    public static readonly Point3D DoorSpot = new({dx}, {dy}, {dz});

    /// <summary>Every piece: art id, x, y, z on the isle ({n} rows).</summary>
    public static readonly (int Id, int X, int Y, int Z)[] Pieces =
    [
{rows}
    ];
}}
""".format(sx=FARM_SHIFT[0], sy=FARM_SHIFT[1], n=len(out), clipped=clipped, ax=ax, ay=ay, dx=dx, dy=dy, dz=dz,
           rows="\n".join(out))
    dest = os.path.join(code, "server", "customizations", "Tutorial", "TutorialIsleFarmLayout.cs")
    with open(dest, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    zs = sorted(int(r.split(",")[3].strip(" )")) for r in out)
    print("wrote %s: %d pieces, z %d..%d, door %s, %d below old ground" % (dest, len(out), zs[0], zs[-1], (dx, dy, dz), clipped))


if __name__ == "__main__":
    main()
