# cc-P54 Part C: uses (and minutes) to re-climb one skill to a previous peak under the decided echo.
# Not part of the server tree. Deterministic (expected values). Run: python reclimb.py > reclimb_out.md
# Gain model: pinned SkillCheck.CheckSkill (UOContent/Skills/SkillCheck.cs:126-137 at d4531cd94) and Gain
# (:236-282), plus ClusterFSkillGain (C\ClusterFSkillGain.cs: attempts re-run the whole check, amount repeats Gain()).
from xp_ladder import CAPS, echo, keeper_echo, RATES, gc

SECONDS_PER_USE = {  # typical use rates, ours (stated in the notes); a use = one check of the skill
    "combat": 3.0, "magic": 5.0, "craft/gather": 5.0, "thief/healer": 8.0, "animal/bard": 8.0,
}
CHANCE = 0.5          # P20's "hard" use; a use whose ceiling is above the peak (Part B gives every skill one)
OTHERS = 6            # six other skills at the cap (sets Skills.Total); total cap = 58 x cap

def per_use(base, cap, r, mult, mode):
    """Expected points per use. mode 'amount': echo multiplies the points of each gain (amount).
    mode 'chance': echo multiplies the gain chance (GainFactor), each roll at most certain."""
    total, totalcap = OTHERS * cap + base, 58 * cap
    if base < 10.0:
        p, per_gain = 1.0, 0.25 * r["amount"]
    else:
        gf = r["gf"] * (mult if mode == "chance" else 1.0)
        p = CHANCE * min(1.0, gc(base, cap, total, totalcap, CHANCE, True, gf)) + \
            (1 - CHANCE) * min(1.0, gc(base, cap, total, totalcap, CHANCE, False, gf))
        per_gain = 0.1 * r["amount"]
    pts = r["attempts"] * p * per_gain
    return pts * (mult if mode == "amount" else 1.0)

def uses(peak, cap, r, mult, mode="amount", start=0.0):
    b, n = start, 0
    while b < peak - 1e-9:
        b = min(cap, b + per_use(b, cap, r, mult, mode))
        n += 1
    return n

CASES = [("no echo", 1.0, None)]
CASES += [(f"base echo, loop {n}", echo(n), n) for n in (1, 5, 10, 18)]
CASES += [(f"Keeper echo, loop {n}", keeper_echo(n), n) for n in (1, 11, 21)]

def reachable(peak, loop):
    """Can a character in `loop` have an earlier peak of `peak`? It needs an earlier loop whose cap >= peak."""
    if loop is None: return True
    return any(CAPS[k] >= peak for k in range(loop))

def cap_for(peak, loop):
    return max(peak, CAPS[loop] if loop is not None else 200)

if __name__ == "__main__":
    print("## Part C model output (generated by notes\\cc-P54-scratch\\reclimb.py)\n")
    print("One skill from 0 to a previous peak, at a 50% success use whose ceiling is above the peak, six other "
          "skills at the cap. Echo as an amount multiplier (each gain worth echo x the points). A cell marked * is "
          "not reachable on the ladder: no earlier loop had a cap that high (peak 150 first exists at loop 11, so "
          "it can be re-climbed from loop 12; peak 200 only after the capstone).\n")
    for rn in ("live", "test", "plain"):
        r = RATES[rn]
        print(f"### Uses to re-climb, rates = {rn} ({r['attempts']} attempt(s), x{r['amount']} amount, GainFactor x{r['gf']:g})\n")
        print("| case | echo | to 100 | to 150 | to 200 |")
        print("|---|---|---|---|---|")
        for name, m, loop in CASES:
            cells = []
            for peak in (100, 150, 200):
                u = uses(peak, cap_for(peak, loop), r, m)
                cells.append(f"{u:,}{'' if reachable(peak, loop) else ' *'}")
            print(f"| {name} | x{m:.2f} | " + " | ".join(cells) + " |")
        print()

    print("### Minutes to re-climb at live rates, by skill group (uses x seconds per use)\n")
    print("Seconds per use: " + ", ".join(f"{g} {s:g}" for g, s in SECONDS_PER_USE.items()) + ".\n")
    print("| case | peak | " + " | ".join(SECONDS_PER_USE) + " |")
    print("|---|---|" + "---|" * len(SECONDS_PER_USE))
    r = RATES["live"]
    for name, m, loop in CASES:
        for peak in (100, 150, 200):
            if not reachable(peak, loop) and loop is not None:
                continue
            u = uses(peak, cap_for(peak, loop), r, m)
            print(f"| {name} | {peak} | " + " | ".join(f"{u*s/60:.1f}" for s in SECONDS_PER_USE.values()) + " |")
    # the late Keeper case that does exist: loop 21, previous peak 195
    for name, m, loop in (("Keeper echo, loop 21", keeper_echo(21), 21), ("base echo, loop 21", echo(21), 21)):
        u = uses(195, 200, r, m)
        print(f"| {name} | 195 | " + " | ".join(f"{u*s/60:.1f}" for s in SECONDS_PER_USE.values()) + " |")
    print()

    print("### Same at plain 1x (pinned alone, no ClusterF), minutes\n")
    print("| case | peak | " + " | ".join(SECONDS_PER_USE) + " |")
    print("|---|---|" + "---|" * len(SECONDS_PER_USE))
    r = RATES["plain"]
    for name, m, loop in CASES:
        for peak in (100, 150):
            if not reachable(peak, loop) and loop is not None:
                continue
            u = uses(peak, cap_for(peak, loop), r, m)
            print(f"| {name} | {peak} | " + " | ".join(f"{u*s/60:.1f}" for s in SECONDS_PER_USE.values()) + " |")
    for name, m, loop in (("Keeper echo, loop 21", keeper_echo(21), 21), ("base echo, loop 21", echo(21), 21)):
        u = uses(195, 200, r, m)
        print(f"| {name} | 195 | " + " | ".join(f"{u*s/60:.1f}" for s in SECONDS_PER_USE.values()) + " |")
    print()

    print("### Echo as a chance multiplier instead (GainFactor x echo): it saturates\n")
    print("Uses to re-climb 0 -> 150 at live rates (cap 155), amount mode vs chance mode.\n")
    print("| echo | amount mode | chance mode |")
    print("|---|---|---|")
    for m in (1, 1.5, 2, 3, 6, 10, 25.75, 50):
        print(f"| x{m:g} | {uses(150, 155, RATES['live'], m, 'amount'):,} | {uses(150, 155, RATES['live'], m, 'chance'):,} |")
    print()

    print("### Whole-character Keeper re-climb at loop 21 (all 58 skills to peak 195, live rates)\n")
    print("| echo | uses per skill | hours for 58 skills at 5 s per use |")
    print("|---|---|---|")
    for m in (1, 10, 20, 50):
        u = uses(195, 200, RATES["live"], m)
        print(f"| x{m:g} | {u:,} | {58*u*5/3600:.1f} |")
    print()

    print("### What Keeper echo at loop 21 gives a target re-climb time (one skill, 0 -> 195, 5 s per use)\n")
    print("| rates | 2 min | 5 min | 15 min |")
    print("|---|---|---|---|")
    for rn in ("live", "plain"):
        row = []
        for minutes in (2, 5, 15):
            target_uses = minutes * 60 / 5.0
            lo, hi = 1.0, 2000.0
            if uses(195, 200, RATES[rn], lo) <= target_uses:
                row.append("x1 already"); continue
            for _ in range(60):
                mid = (lo + hi) / 2
                if uses(195, 200, RATES[rn], mid) > target_uses: lo = mid
                else: hi = mid
            row.append(f"x{hi:.1f}")
        print(f"| {rn} | " + " | ".join(row) + " |")
    print()
