out.append('- 0xA854, %s,%s, ground Z, faces south: the lodge\'s name sign "The League lodge", north of the road by the lodge door, beside the League lesson sign (cc-P751)' % m.groups())
out += ['', "## The wreck (WakeningIsleShipwreckAddon at 6624,3995,-4, OSI's Malas composition)", '']
