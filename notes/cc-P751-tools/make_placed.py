    "farmhouse door: DarkWoodDoor WestCCW (0x06A9), 6702,3978,7, the south wall; open, it folds west along the wall "
    "line (was WestCW 0x06A5, which swung out); a world's old door is rehung in place",
    "League lodge sign: 0xA854 named \"The League lodge\", 6781,3989, ground Z, faces south to the road, north of the road "
