"""cc-P742: generates the vision chamber's piece table, server/customizations/Tutorial/TutorialVisionChamberLayout.cs, and
notes/cc-P742-review/placed.md. The room is OSI's dungeon brick (survey_dungeon.py: 0x0241 east-west, 0x0242
north-south, 0x0244 post, 0x0243 corner, laid by the guide's corner rule 2.2), floored with grey pavers round the shrine
and cave floor at the edges (OSI's dungeons use both), dressed from the guide's Shrine and Dungeon lists.
Usage: python -P gen_chamber.py <code copy> <docs copy>"""
import sys

code, docs = sys.argv[1], sys.argv[2]
N = 8  # the wall box is 0..8 on both axes; floor 1..8 (inside, and under the south row and east column)
pieces = []  # (id, dx, dy, dz, what, wall/facing note)


def add(tid, x, y, z, what, note=""):
    pieces.append((tid, x, y, z, what, note))


# floor: grey pavers on the shrine's 5x5, cave floor round it (a fixed pattern, so the table is stable)
PAVERS = (0x051D, 0x0519, 0x051D, 0x051D)
CAVE = (0x053D, 0x053F, 0x053B, 0x053D, 0x053C, 0x053F)
for x in range(1, N + 1):
    for y in range(1, N + 1):
        if 2 <= x <= 6 and 2 <= y <= 6:
            add(PAVERS[(x * 3 + y * 5) % len(PAVERS)], x, y, 0, "grey pavers", "floor")
        else:
            add(CAVE[(x * 7 + y * 11) % len(CAVE)], x, y, 0, "cave floor", "floor")

# walls: post NW, east-west pieces along the north row to the NE tile and along the south row, north-south pieces down the
# west column to the SW tile and down the east column, the corner at SE
add(0x0244, 0, 0, 0, "dungeon wall post", "north-west corner")
for x in range(1, N + 1):
    add(0x0241, x, 0, 0, "dungeon wall, east-west", "north wall")
for y in range(1, N + 1):
    add(0x0242, 0, y, 0, "dungeon wall, north-south", "west wall")
for x in range(1, N):
    add(0x0241, x, N, 0, "dungeon wall, east-west", "south wall")
for y in range(1, N):
    add(0x0242, N, y, 0, "dungeon wall, north-south", "east wall")
add(0x0243, N, N, 0, "dungeon wall corner", "south-east corner")

# the shrine
add(0x1223, 4, 4, 0, "pedestal (the Gem stands on it)", "centre")
for tid, x, y in ((0x0E5D, 4, 2), (0x0E60, 2, 4), (0x0E63, 6, 4), (0x0E66, 4, 6)):
    add(tid, x, y, 0, "glowing rune", "floor, round the pedestal")
add(0x0E31, 6, 2, 0, "brazier (lit)", "north-east of the pedestal")
add(0x0E31, 2, 6, 0, "brazier (lit)", "south-west of the pedestal")

# lights on the walls the camera shows: torches on the floor tile in front of their wall, floor + 13 (guide 3)
add(0x0A0C, 3, 1, 13, "wall torch", "north wall, faces south")
add(0x0A0C, 6, 1, 13, "wall torch", "north wall, faces south")
add(0x0A07, 1, 3, 13, "wall torch", "west wall, faces east")
add(0x0A07, 1, 6, 13, "wall torch", "west wall, faces east")

# a forgotten shrine: broken pillars in two corners, bones by the walls, stalagmites
add(0x45B5, 7, 1, 0, "broken pillar", "north-east corner")
add(0x45B4, 1, 7, 0, "broken pillar", "south-west corner")
add(0x0ECB, 7, 4, 0, "bones", "by the east wall")
add(0x0ECE, 3, 7, 0, "bones", "by the south wall")
add(0x0ED1, 5, 1, 0, "bones", "by the north wall")
add(0x08E1, 7, 7, 0, "stalagmites", "south-east corner, behind the onlooker")
add(0x08E4, 1, 4, 0, "stalagmites", "by the west wall")

# no two pieces of one kind on a tile, and nothing on the walked or watched tiles
KEEP_CLEAR = {(1, 1): "the Stranger's start", (2, 2): "his walk", (3, 3): "where he strikes", (6, 6): "the onlooker",
              (5, 5): "the line of sight and the echo"}
for (tid, x, y, z, what, note) in pieces:
    if (x, y) in KEEP_CLEAR and "floor" not in note:
        raise SystemExit("%s at %d,%d blocks %s" % (what, x, y, KEEP_CLEAR[(x, y)]))

lines = ",\n".join("        {{ 0x{0:04X}, {1}, {2}, {3} }}".format(t, x, y, z) for (t, x, y, z, _, _) in pieces)
cs = """// GENERATED by shard-migration notes/cc-P742-tools/gen_chamber.py. Do not edit by hand: change the generator and rerun it.
// cc-P742 (Chase 10-30): the vision's dungeon shrine, {n} pieces relative to the chamber's north-west corner (the wall
// post), at the chamber's floor height. Rows are {{ item id, x, y, z }}. Placed per scene by TutorialVisionChamber.Build.

namespace Server.Tutorial;

public static class TutorialVisionChamberLayout
{{
    public static readonly int[][] Pieces =
    [
{rows}
    ];
}}
""".format(n=len(pieces), rows=lines.replace("{ ", "[ ").replace(" }", " ]"))
# keep a "{ id, x, y, z }" copy in a comment block too, so render_addons.py reads the table as it reads addon scripts
cs += "\n/* render_addons.py reads these rows:\n" + "\n".join("{{ {0}, {1}, {2}, {3} }}".format(t, x, y, z) for (t, x, y, z, _, _) in pieces) + "\n*/\n"
open(code + "/server/customizations/Tutorial/TutorialVisionChamberLayout.cs", "w", encoding="utf-8", newline="\n").write(cs)

md = ["# cc-P742: the vision chamber, every placed piece", "",
      "Relative to the chamber's north-west corner (the wall post). Slot k's corner is x = 6170 + 28 k, y = 3752, Z 0, on",
      "the player's own lesson map (the Fold or their private copy). Generated by `notes/cc-P742-tools/gen_chamber.py`.",
      "Nothing was turned from its art: each wall piece is OSI's own for its run (survey_dungeon.py).", "",
      "| Item | x, y, z | What | Wall or place |", "|---|---|---|---|"]
for (t, x, y, z, what, note) in pieces:
    if note == "floor":
        continue
    md.append("| 0x%04X | %d, %d, %d | %s | %s |" % (t, x, y, z, what, note))
floor = [p for p in pieces if p[5] == "floor"]
md += ["", "Floor: %d tiles at Z 0 (x 1-8, y 1-8): grey pavers 0x051D/0x0519 on x 2-6, y 2-6, cave floor 0x053B-0x053F round them." % len(floor), "",
       "Scene spots (not pieces): the Stranger starts at 1,1, walks 2,2 then 3,3 and strikes facing south-east; the",
       "onlooker (the player, hidden) stands at 6,6 facing north-west; the echo appears at 5,5; the hooded figure at 2,2;",
       "the broken sword falls at 3,4. Kept clear of every piece but the floor: " + ", ".join("%d,%d" % k for k in KEEP_CLEAR) + ".",
       "", "Windows: none (a dungeon room). Doors: none (sealed; the void round it cannot be walked)."]
open(docs + "/notes/cc-P742-review/placed.md", "w", encoding="utf-8", newline="\n").write("\n".join(md) + "\n")
print(len(pieces), "pieces;", len(floor), "floor")
