# cc-P19: generates the League field office layout for the shard from the design file, the only source of
# truth, in the form cc-P16 set (notes/cc-P16-tools/gen_layout.py):
#   D:/ShatteredLegacy/design/registrar-office/layout.json
#     -> server/customizations/ClusterFRegistrarOfficeLayout.cs     (the table the server uses)
#     -> server/tests/Misc/RegistrarOfficeLayoutDesignCopy.cs        (the design file verbatim, for the test)
# The test parses the verbatim copy and compares it with the table component for component, and checks
# the copy's SHA-256 against the hash recorded here. Re-run this after any change to layout.json.
# Hash: SHA-256 of the file's text with CRLF normalized to LF and trailing newlines removed.
import hashlib, json
ROOT = r'D:/ShatteredLegacy'
DESIGN = ROOT + '/design/registrar-office/layout.json'
raw = open(DESIGN, 'rb').read().decode('ascii')          # ASCII only; fails loudly otherwise
text = raw.replace('\r\n', '\n').rstrip('\n')
sha = hashlib.sha256(text.encode('ascii')).hexdigest()
L = json.loads(text)
assert '"""' not in text

AREAS = ['outside', 'office', 'quarters']                 # one addon per area, in this order
assert sorted(set(c['area'] for c in L['components'])) == sorted(AREAS), set(c['area'] for c in L['components'])

def q(s): return json.dumps(s)

out = []
w = out.append
w('// Generated by shard-migration notes/cc-P19-tools/gen_office_layout.py from design/registrar-office/layout.json.')
w('// Do not edit by hand: change the design file and re-run the generator. The test')
w('// RegistrarOfficeVerification.TheLoadedLayoutIsTheDesignFile compares this table with the design file.')
w('//')
w('// The layout is a C# table, not a data file, for cc-P16\'s reason: the build installs only .cs files from')
w('// server/customizations (docker/uo/apply-patches.sh, mirror_cs_tree), and Distribution/Data is pinned.')
w('// Components use cc-P16\'s MineCampComponent record (ClusterFMineCampLayout.cs); Group is the design\'s area.')
w('')
w('namespace Server;')
w('')
w('public static class ClusterFRegistrarOfficeLayout')
w('{')
w('    public const string DesignFile = "design/registrar-office/layout.json";')
w(f'    public const string DesignSha256 = "{sha}";')
w(f'    public const string MapName = {q(L["map"])};')
w('')
w('    // In design order.')
w('    public static readonly MineCampComponent[] Components =')
w('    [')
for c in L['components']:
    w(f'        new({q(c["area"])}, 0x{int(c["id"], 16):04X}, {q(c["name"])}, {c["x"]}, {c["y"]}, {c["z"]}),')
w('    ];')
w('')
for a in AREAS:
    nm = a.capitalize()
    w(f'    public static readonly MineCampComponent[] {nm} =')
    w('    [')
    for c in L['components']:
        if c['area'] == a:
            w(f'        new({q(c["area"])}, 0x{int(c["id"], 16):04X}, {q(c["name"])}, {c["x"]}, {c["y"]}, {c["z"]}),')
    w('    ];')
    w('')
w('    public static readonly (string Area, MineCampComponent[] Components)[] Areas =')
w('    [')
for a in AREAS:
    w(f'        ({q(a)}, {a.capitalize()}),')
w('    ];')
w('}')
open(ROOT + '/server/customizations/ClusterFRegistrarOfficeLayout.cs', 'w', newline='\n').write('\n'.join(out) + '\n')

t = []
t.append('// Generated by shard-migration notes/cc-P19-tools/gen_office_layout.py. Do not edit by hand.')
t.append('//')
t.append('// design/registrar-office/layout.json, verbatim. The test container holds server/tests but not design/')
t.append('// (docker/uo/Dockerfile copies only server/customizations, server/tests, server/migrations and')
t.append('// server/patches), so the design file reaches the test as this copy. Its SHA-256 is checked against')
t.append('// the hash the generator recorded from the design file.')
t.append('')
t.append('namespace ShatteredLegacy.Tests;')
t.append('')
t.append('internal static class RegistrarOfficeLayoutDesignCopy')
t.append('{')
t.append(f'    public const string Sha256 = "{sha}";')
t.append('')
t.append('    public const string Json =')
t.append('"""')
t.append(text)
t.append('""";')
t.append('}')
open(ROOT + '/server/tests/Misc/RegistrarOfficeLayoutDesignCopy.cs', 'w', newline='\n').write('\n'.join(t) + '\n')
print('components:', len(L['components']), {a: sum(c['area'] == a for c in L['components']) for a in AREAS}, 'sha256:', sha)
