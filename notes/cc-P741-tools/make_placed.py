"""cc-P741: notes/cc-P741-review/placed.md, one line per placed piece, from the sources (isle-sets.json interiors,
TutorialIsleFarmLayout.cs, TutorialIsleAddons.cs, TutorialCorePlacement.cs, TutorialFarm.cs). python -P make_placed.py"""
import json, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
SETS = json.load(open(os.path.join(HERE, '..', 'cc-P662-tools', 'isle-sets.json'), encoding='utf-8'))
TUT = 'D:/UO/golems/Iron/ShatteredLegacy/server/customizations/Tutorial/'
out = ['# cc-P741 placed pieces', '',
       'One line per piece: item ID, x,y,z (the lesson map, the Fold and every copy), facing or wall, what it is. '
       'Generated by `notes/cc-P741-tools/make_placed.py` from the sources.', '']
out += ['## Lesson signs (standing signpost 0xA854, the face that reads from the south; all north of their path)', '']
cp = open(TUT + 'TutorialCorePlacement.cs', encoding='utf-8').read()
for k, x, y in re.findall(r'"(core\.\w+)" => new Point2D\((\d+), (\d+)\),', cp):
    out.append('- 0xA854, %s,%s, ground Z, faces south to its path: %s lesson sign' % (x, y, k))
m = re.search(r'HealingSign = new\((\d+), (\d+)\)', cp)
out.append('- 0xA854, %s,%s, ground Z, faces south to the road: core.healing lesson sign (south-west of the farmhouse steps)' % m.groups())
out.append('- 0xA854, 6690,3986, ground Z, faces south: the chat lesson\'s farm signpost ("say \'I am ready to learn\'"), beside its lesson sign')
out.append('- 0xA854, 6697,3977, 0, faces south: the farm gate\'s signpost (in the farm addon), beside Wren')
out += ['', '## The wreck (WakeningIsleShipwreckAddon at 6624,3995,-4, OSI\'s Malas composition)', '']
ad = open(TUT + 'TutorialIsleAddons.cs', encoding='utf-8').read()
body = ad[ad.index('class WakeningIsleShipwreckAddon'):]
body = body[body.index('Pieces ='):body.index('];')]
names = {range(0x47B8, 0x47D6): 'West half (ShipwreckBow WEST)', range(0x48A4, 0x4910): 'East half (ShipwreckBow EAST)'}
for t, dx, dy, dz in re.findall(r'\((\d+), (-?\d+), (-?\d+), (-?\d+)\)', body):
    t = int(t)
    what = next((n for r, n in names.items() if t in r), {0x0C2D: 'driftwood', 0x0C2E: 'driftwood', 0x0C2F: 'driftwood',
                0x0C30: 'driftwood', 0x1FBC: 'wave in the break', 0x1FC5: 'wave in the break', 0x3492: 'swirl in the break',
                0x0D34: 'seaweed (morning glories)'}.get(t, 'piece'))
    out.append('- 0x%04X, %d,%d,%d, as OSI lays it: %s' % (t, 6624 + int(dx), 3995 + int(dy), -4 + int(dz), what))
for name, title in (('bank', 'The bank (map statics; floor x 6758-6766, y 3973-3979, door 6762,3980 south)'),
                    ('lodge', 'The League lodge (map statics; floor x 6778-6786, y 3996-4002, door 6782,3995 north)')):
    out += ['', '## ' + title, '']
    for t, x, y, z, what in SETS['interiors'][name]['pieces']:
        out.append('- %s, %d,%d,%d, %s' % (t, x, y, z, what))
out += ['', '## The bank\'s ground (map land)', '',
        '- paved: the bank\'s footprint, the apron x 6759-6765, y 3981-3982, the fountain pad x 6767-6769, y 3983-3985',
        '- worn dirt round each paved patch and under the smithy corner x 6768-6770, y 3974-3978; grass elsewhere (it was a 21 x 18 paved square)',
        '- the lodge floor: 0x04A9 on every floor tile, the door tile and under the south row and east column of its walls']
out += ['', '## The farm (TutorialIsleFarmLayout.cs, the addon at 6691,3975,0; generated by gen_isle_farm.py)', '']
lay = open(TUT + 'TutorialIsleFarmLayout.cs', encoding='utf-8').read()
for t, x, y, z, n in re.findall(r'\((0x[0-9A-F]+), (\d+), (\d+), (-?\d+)\), // (.*)', lay):
    out.append('- %s, %s,%s,%s, %s' % (t, x, y, z, n))
out += ['', '## The farm\'s server pieces (TutorialFarm.cs)', '',
        '- field gate (TutorialPestGate, NorthCCW), 6695,3979: one gate in the east fence\'s gap; fence piece 0x0837 at 6695,3978',
        '- Wren 6696,3978 (faces east); Tobin 6696,3976; pest spawner 6684,3978 range 3; pen spawner 6691,3970 range 2',
        '- farmhouse door (DarkWoodDoor WestCW, 0x06A5), 6702,3978,7, the cottage\'s south wall',
        '- Pip on his bench 0x0B2D, 6704,3975,7 and 6704,3976,7 along the east wall; blood 0x122A/0x122D/0x122C at 6703,3974-3976,7',
        '- field beds (map land): x 6679-6693, y 3975-3981 and x 6679-6686, y 3968-3972; furrows 0x0009 inside, OSI\'s border pieces on the edges']
open(os.path.join(HERE, '..', 'cc-P741-review', 'placed.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print(len(out), 'lines')
