# cc-P237 WRITES server/customizations/ClusterFCommunityArtLayout.cs from placement.json and registry.csv, after
# validate.py passes (it refuses to write while any row fails).
import json, os, sys, subprocess, csv
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import art_src as S
SL = 'D:/UO/golems/Bronze/ShatteredLegacy'
OUT = SL + '/server/customizations/ClusterFCommunityArtLayout.cs'
REG = SL + '/player-package/vendor/shattered-legacy-art/registry.csv'
r = subprocess.run([sys.executable, '-P', os.path.join(HERE, 'validate.py')], capture_output=True, text=True)
if r.returncode:
    sys.exit('validate.py fails; not writing:\n' + r.stdout[-2000:])
rows = json.load(open(os.path.join(HERE, 'placement.json')))
reg = [int(x['id']) for x in csv.DictReader(l for l in open(REG, encoding='ascii') if not l.startswith('#'))
       if x['kind'] == 'art' and S.FIRST <= int(x['id']) <= S.LAST]


def cs(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


lines = [
    '// GENERATED by shard-migration notes/cc-P237-tools/gen_layout.py from placement.json and registry.csv. Do not edit',
    '// by hand: change placement.json, run validate.py (the map checks), then gen_layout.py.',
    '//',
    '// cc-P237 (F-21): New Haven\'s community art, one row per item, all on Trammel. Every row was checked against the',
    '// server\'s own map files: the surface at its z, nothing impassable in the way, off the roads (but the steps\' railing),',
    '// not a door, a door\'s swing tile, a seeded tile, a pinned spawner or its ring, a pinned decoration or P188\'s walk;',
    '// paintings only on a north wall with no OSI wall art beside them; the orc camp outside every creature spawner\'s',
    '// walking box. The table with a reason per row is in the cc-P237 notes.',
    '',
    'namespace Server;',
    '',
    'public static class ClusterFCommunityArtLayout',
    '{',
    '    public sealed record Row(string Key, string Area, int X, int Y, int Z, int ItemId, string Name);',
    '',
    '    public static readonly Row[] Rows =',
    '    {',
]
for x in rows:
    lines.append('        new(%s, %s, %d, %d, %d, 0x%04X, %s),' % (cs(x['key']), cs(x['area']), x['x'], x['y'], x['z'], x['itemId'], cs(x['name'])))
lines += [
    '    };',
    '',
    '    // The art IDs registry.csv registers for this set (%d, 0x%04X-0x%04X): a row may use only these.' % (len(reg), S.FIRST, S.LAST),
    '    public static readonly int[] RegisteredIds =',
    '    {',
]
for k in range(0, len(reg), 8):
    lines.append('        ' + ', '.join('0x%04X' % i for i in reg[k:k + 8]) + ',')
lines += ['    };', '}', '']
open(OUT, 'w', encoding='ascii', newline='\n').write('\n'.join(lines))
print('wrote', OUT, len(rows), 'rows,', len(reg), 'registered IDs')
