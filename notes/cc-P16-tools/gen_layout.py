# cc-P16: generates the mine-camp layout for the shard from the design file, the only source of truth.
#   D:/ShatteredLegacy/design/mine-camp-tents/layout.json
#     -> server/customizations/ClusterFMineCampLayout.cs     (the table the server uses)
#     -> server/tests/Misc/MineCampLayoutDesignCopy.cs        (the design file verbatim, for the test)
# The test parses the verbatim copy and compares it with the table component for component, and checks
# the copy's SHA-256 against the hash recorded here. Re-run this after any change to layout.json.
# Hash: SHA-256 of the file's text with CRLF normalized to LF and trailing newlines removed.
import hashlib, json, sys
ROOT = r'D:/ShatteredLegacy'
DESIGN = ROOT + '/design/mine-camp-tents/layout.json'
raw = open(DESIGN, 'rb').read().decode('ascii')          # ASCII only; fails loudly otherwise
text = raw.replace('\r\n', '\n').rstrip('\n')
sha = hashlib.sha256(text.encode('ascii')).hexdigest()
L = json.loads(text)
assert '"""' not in text

FACING = {'North', 'Right', 'East', 'Down', 'South', 'Left', 'West', 'Up'}

def q(s): return json.dumps(s)  # a C# string literal for ASCII text without escapes beyond \" and \\

out = []
w = out.append
w('// Generated by shard-migration notes/cc-P16-tools/gen_layout.py from design/mine-camp-tents/layout.json.')
w('// Do not edit by hand: change the design file and re-run the generator. The test')
w('// MineCampVerification.TheLoadedLayoutIsTheDesignFile compares this table with the design file.')
w('//')
w('// The layout is a C# table, not a data file, because the build installs only .cs files from')
w('// server/customizations (docker/uo/apply-patches.sh, mirror_cs_tree), and Distribution/Data is pinned.')
w('')
w('namespace Server;')
w('')
w('public static class ClusterFMineCampLayout')
w('{')
w(f'    public const string DesignFile = "design/mine-camp-tents/layout.json";')
w(f'    public const string DesignSha256 = "{sha}";')
w(f'    public const string MapName = {q(L["map"])};')
w('')
for a in L['addons']:
    w(f'    public static readonly MineCampComponent[] {a["name"]} =')
    w('    [')
    for c in a['components']:
        iid = int(c['id'], 16)
        w(f'        new({q(c["group"])}, 0x{iid:04X}, {q(c["name"])}, {c["x"]}, {c["y"]}, {c["z"]}),')
    w('    ];')
    w('')
w('    public static readonly (string Name, MineCampComponent[] Components)[] Addons =')
w('    [')
for a in L['addons']:
    w(f'        ({q(a["name"])}, {a["name"]}),')
w('    ];')
w('')
w('    public static readonly MineCampNpcMove[] Npcs =')
w('    [')
for n in L['npcs']:
    assert n['facing'] in FACING, n['facing']
    f, t = n['from'], n['to']
    w(f'        new({q(n["type"])}, new Point3D({f[0]}, {f[1]}, {f[2]}), new Point3D({t[0]}, {t[1]}, {t[2]}), Direction.{n["facing"]}),')
w('    ];')
w('}')
w('')
w('public sealed record MineCampComponent(string Group, int ItemID, string Name, int X, int Y, int Z)')
w('{')
w('    public Point3D Location => new(X, Y, Z);')
w('}')
w('')
w('public sealed record MineCampNpcMove(string TypeName, Point3D From, Point3D To, Direction Facing);')
open(ROOT + '/server/customizations/ClusterFMineCampLayout.cs', 'w', newline='\n').write('\n'.join(out) + '\n')

t = []
t.append('// Generated by shard-migration notes/cc-P16-tools/gen_layout.py. Do not edit by hand.')
t.append('//')
t.append('// design/mine-camp-tents/layout.json, verbatim. The test container holds server/tests but not design/')
t.append('// (docker/uo/Dockerfile copies only server/customizations, server/tests, server/migrations and')
t.append('// server/patches), so the design file reaches the test as this copy. Its SHA-256 is checked against')
t.append('// the hash the generator recorded from the design file.')
t.append('')
t.append('namespace ShatteredLegacy.Tests;')
t.append('')
t.append('internal static class MineCampLayoutDesignCopy')
t.append('{')
t.append(f'    public const string Sha256 = "{sha}";')
t.append('')
t.append('    public const string Json =')
t.append('"""')
t.append(text)
t.append('""";')
t.append('}')
open(ROOT + '/server/tests/Misc/MineCampLayoutDesignCopy.cs', 'w', newline='\n').write('\n'.join(t) + '\n')
print('components:', {a['name']: len(a['components']) for a in L['addons']}, 'npcs:', len(L['npcs']), 'sha256:', sha)
